import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const code=ts.transpileModule(readFileSync('src/lib/manual-data-refresh.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2020}}).outputText;
const sandbox={exports:{},require:()=>({}),Promise,Map,Set};
vm.runInNewContext(code,sandbox);
const {registerManualRefresh,refreshVisibleData}=sandbox.exports;
let calls=0,otherCalls=0,release;
const hold=new Promise(resolve=>{release=resolve;});
const dispose=registerManualRefresh('planning',async()=>{calls++;await hold;});
const disposeOther=registerManualRefresh('history',async()=>{otherCalls++;});
assert.equal(calls,0,'registration must not make a query');
const first=refreshVisibleData('planning');const second=refreshVisibleData('planning');
assert.equal(first,second,'repeated clicks must share the same in-flight request');
await Promise.resolve();assert.equal(calls,1);assert.equal(otherCalls,0,'scoped refresh must not load other areas');
release();await first;
dispose();await refreshVisibleData('planning');assert.equal(calls,1,'unmounted area must not receive updates');
const blocked=registerManualRefresh('blocked',async()=>{calls++;},true);
await refreshVisibleData();assert.equal(calls,1);assert.equal(otherCalls,0,'blocked editing operation must prevent refresh');
blocked();await refreshVisibleData();assert.equal(otherCalls,1);
const old=registerManualRefresh('duplicate',async()=>{calls++;});
const newer=registerManualRefresh('duplicate',async()=>{calls+=10;});old();
await refreshVisibleData('duplicate');assert.equal(calls,11,'cleanup from an old registration must preserve its replacement');
newer();disposeOther();
const failed=registerManualRefresh('failure',async()=>{throw new Error('network');});
await refreshVisibleData('failure');failed();
const recovery=registerManualRefresh('recovery',async()=>{calls++;});
await refreshVisibleData('recovery');assert.equal(calls,12,'network failure must release the in-flight lock');recovery();
console.log('PASS manual-only queries, scoped loaders, click deduplication, edit guard, route cleanup and failure recovery');
