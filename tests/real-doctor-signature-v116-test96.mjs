import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const image='data:image/png;base64,assinatura-original';
const available=[{id:'doctor',name:'Médico',crm:'123',signatureImage:image}];
const exam=readFileSync('src/app/dashboard/exames/page.tsx','utf8');
const marker='  }, [selectedDoctorId, availableDoctors, signatureImage]);';
const end=exam.indexOf(marker);const start=exam.lastIndexOf('  useEffect(() => {',end)+'  useEffect(() => {'.length;
const healExam=new Function('availableDoctors','selectedDoctorId','draftHydratedRef','draftDoctorRef','signatureImage','setSignatureImage','setDoctor',stripTypeScriptTypes('function run(){'+exam.slice(start,end)+'}')+';return run();');
let received=null;
healExam(available,'doctor',{current:true},{current:'doctor'},null,value=>received=value,()=>{});
assert.equal(received,image,'Restored empty draft must use registered signature');
received=null;healExam(available,'doctor',{current:true},{current:'doctor'},'data:image/png;base64,temporaria',value=>received=value,()=>{});
assert.equal(received,null,'Original temporary signature is preserved');
const doc=readFileSync('src/app/dashboard/documentos/page.tsx','utf8');
const docEnd=doc.indexOf('  }, [selectedDoctorId, availableDoctors, doctor.signatureImage]);');
const docStart=doc.lastIndexOf('  useEffect(() => {',docEnd)+'  useEffect(() => {'.length;
const healDocument=new Function('availableDoctors','selectedDoctorId','restoredDoctor','doctor','setDoctor',stripTypeScriptTypes('function run(){'+doc.slice(docStart,docEnd)+'}')+';return run();');
let doctor={name:'Nome recuperado',signatureImage:null};
healDocument(available,'doctor',{current:'doctor'},doctor,value=>doctor=typeof value==='function'?value(doctor):value);
assert.equal(doctor.signatureImage,image);assert.equal(doctor.name,'Nome recuperado');
assert(!readFileSync('src/lib/exam-page-canvas.ts','utf8').includes('italic 26px Georgia'));
assert(!readFileSync('src/lib/document-page-canvas.ts','utf8').includes('italic 22px Georgia'));
console.log('PASS restored exam/document drafts heal from registered image, temporary assets preserved, generic handwritten fallback removed');
